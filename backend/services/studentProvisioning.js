/**
 * studentProvisioning.js
 * ----------------------
 * The SINGLE place that creates admin-made students and their login accounts.
 * Every path builds the Firestore profile through buildStudentProfile()
 * (services/studentProfile.js), so an imported student is identical in schema to
 * a manually registered one — there is no second, drifting copy of the shape.
 *
 * Two creation orders, chosen per path:
 *
 *   provisionStudent()          — INDIVIDUAL registration (admin types a temporary
 *                                 password). Auth first, then profile: the form
 *                                 must fail as a whole (e.g. email already used),
 *                                 so nothing is written unless the account exists.
 *                                 If the profile write fails, the just-created
 *                                 Auth user is rolled back (no orphan account).
 *
 *   provisionImportedStudent()  — BULK import. The student RECORD is the priority:
 *                                 the Auth user is created with uid = the
 *                                 pre-allocated profile id, then the profile is
 *                                 written ONCE with the real outcome. An Auth
 *                                 failure never loses the record — it is stored as
 *                                 authAccountStatus:'failed' and recovered later
 *                                 by issueStudentCredentials() with the SAME uid,
 *                                 so a retry can never create a duplicate record
 *                                 or a second account.
 *
 *   issueStudentCredentials()   — recovery: create the missing account (student
 *                                 imported without email / failed creation), or
 *                                 issue a NEW temporary password while the student
 *                                 has not yet replaced the admin-issued one.
 *
 * Passwords: generated by temporaryPassword.js (crypto), handed straight to
 * Firebase Auth (which hashes them) and returned to the caller exactly once.
 * They are never written to Firestore and never logged.
 */

const { admin, db, auth } = require('../config/firebase');
const { normalizeSchool } = require('../constants');
const {
  BRANCH_NAMES, AUTH_ACCOUNT, generateRegistrationNumber, buildStudentProfile,
} = require('./studentProfile');
const { generateTemporaryPassword } = require('./temporaryPassword');
const { EMAIL_RE } = require('./studentFields');

const VALID_BRANCHES = ['boumerdes', 'bordj_menaiel'];

const ts = { now: () => admin.firestore.FieldValue.serverTimestamp() };
const usersCol = (branchId) => db.collection('branches').doc(branchId).collection('users');

/** Arabic, admin-facing explanation of an Auth failure (code only — no secrets). */
const ACCOUNT_ERROR_MESSAGES = {
  'auth/email-already-exists': 'البريد الإلكتروني مستخدم في حساب دخول آخر',
  'auth/invalid-email':        'البريد الإلكتروني غير مقبول لدى نظام تسجيل الدخول',
  'auth/invalid-password':     'كلمة المرور المؤقتة مرفوضة من نظام تسجيل الدخول',
  'auth/quota-exceeded':       'تم بلوغ حد إنشاء الحسابات مؤقتاً — أعد المحاولة لاحقاً',
  'auth/too-many-requests':    'تم بلوغ حد إنشاء الحسابات مؤقتاً — أعد المحاولة لاحقاً',
};
const accountErrorMessage = (code) => ACCOUNT_ERROR_MESSAGES[code] || 'تعذّر إنشاء حساب الدخول';

/** Keep only a safe, non-sensitive error code (never a message that could echo input). */
const safeAuthCode = (err) => (err && typeof err.code === 'string' && err.code.startsWith('auth/') ? err.code : 'internal');

const RETRYABLE = new Set(['auth/internal-error', 'auth/quota-exceeded', 'auth/too-many-requests']);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** auth.createUser with one delayed retry on transient errors. */
async function createAuthUser(props) {
  try {
    return await auth.createUser(props);
  } catch (err) {
    if (!RETRYABLE.has(err?.code)) throw err;
    await sleep(1200);
    return auth.createUser(props);
  }
}

/**
 * INDIVIDUAL registration — Auth user + canonical profile.
 *
 * @param {object} p
 * @param {string} p.branchId
 * @param {string} p.fullName
 * @param {string} p.email
 * @param {string} p.password       admin-typed temporary password
 * @param {{uid,name?,email?}} p.callerActor
 * @param {object} [p.profile]      already-validated optional fields
 *        { phone, school, birthDate, birthPlace, address, studyYear, academicYear }
 * @returns {Promise<{uid, registrationNumber, normalizedEmail, trimmedName, normalizedSchool}>}
 */
async function provisionStudent({ branchId, fullName, email, password, callerActor, profile = {}, phone, school }) {
  const normalizedEmail  = email.trim().toLowerCase();
  const trimmedName      = fullName.trim();
  // `phone`/`school` top-level args kept for backward compatibility with older callers.
  const p = { phone, school, ...profile };
  const normalizedSchool = normalizeSchool(p.school);

  const userRecord = await auth.createUser({
    email:         normalizedEmail,
    password,
    displayName:   trimmedName,
    emailVerified: true,
  });
  const uid = userRecord.uid;
  const registrationNumber = generateRegistrationNumber(branchId);

  try {
    await usersCol(branchId).doc(uid).set(buildStudentProfile({
      uid, branchId, fullName: trimmedName, email: normalizedEmail,
      phone: p.phone, school: normalizedSchool,
      birthDate: p.birthDate, birthPlace: p.birthPlace, address: p.address,
      studyYear: p.studyYear, academicYear: p.academicYear,
      registrationNumber, callerActor,
      // The admin-typed password is a TEMPORARY one: the student replaces it at first login.
      account: { status: AUTH_ACCOUNT.ACTIVE, mustChangePassword: true },
    }, ts));
  } catch (err) {
    // Never leave a login account without its profile.
    await auth.deleteUser(uid).catch(() => {});
    throw err;
  }

  return { uid, registrationNumber, normalizedEmail, trimmedName, normalizedSchool };
}

/**
 * BULK import — record-first. `candidate` is the normalized row from
 * bulkImportValidation.normalizeRow().
 *
 * @param {object} p
 * @param {string} p.branchId
 * @param {object} p.candidate
 * @param {{uid,name?,email?}} p.callerActor
 * @param {() => string} p.generatePassword   batch-unique generator
 * @returns {Promise<{uid, registrationNumber, account:{status, code?, reason?}, password: ?string}>}
 *          `password` is non-null ONLY when a login account was created.
 * @throws when the profile itself cannot be written (nothing is left behind).
 */
async function provisionImportedStudent({ branchId, candidate, callerActor, generatePassword }) {
  const ref = usersCol(branchId).doc(); // pre-allocated id = future Auth uid
  const uid = ref.id;
  const registrationNumber = generateRegistrationNumber(branchId);

  let account = { status: AUTH_ACCOUNT.NONE };
  let password = null;
  if (candidate.email) {
    password = generatePassword();
    try {
      await createAuthUser({
        uid,
        email:         candidate.email,
        password,
        displayName:   candidate.fullName,
        emailVerified: true,
      });
      account = { status: AUTH_ACCOUNT.ACTIVE, mustChangePassword: true };
    } catch (err) {
      const code = safeAuthCode(err);
      account = { status: AUTH_ACCOUNT.FAILED, error: code, code, reason: accountErrorMessage(code) };
      password = null; // never hand out a password for an account that does not exist
    }
  }

  try {
    await ref.set(buildStudentProfile({
      uid, branchId,
      fullName:     candidate.fullName,
      email:        candidate.email,
      phone:        candidate.phone,
      school:       candidate.school,
      birthDate:    candidate.birthDate,
      birthPlace:   candidate.birthPlace,
      address:      candidate.address,
      studyYear:    candidate.studyYear,
      academicYear: candidate.academicYear,
      distinguishedSubjectsAverage: candidate.distinguishedSubjectsAverage,
      supportClassification:        candidate.supportClassification,
      registrationNumber, callerActor, account,
    }, ts));
  } catch (err) {
    if (account.status === AUTH_ACCOUNT.ACTIVE) await auth.deleteUser(uid).catch(() => {});
    throw err;
  }

  return { uid, registrationNumber, account, password };
}

class CredentialsError extends Error {
  constructor(status, code, message) {
    super(message);
    this.status = status;
    this.code = code;
    this.isCredentialsError = true;
  }
}

/**
 * Recovery for an admin-created student's login.
 *
 *   • No Auth user for this uid  → create it (uid = profile id, so every record
 *     that already references the student stays valid). Requires an email —
 *     taken from the request (students imported without one) or the profile.
 *   • Auth user exists           → issue a NEW temporary password, but ONLY while
 *     the student still has the admin-issued one (createdByAdmin +
 *     mustChangePassword). Once a student has set their own password, the admin
 *     can never overwrite it — the student uses «نسيت كلمة المرور» instead.
 *
 * @returns {Promise<{action:'created'|'reset', uid, name, email, temporaryPassword}>}
 * @throws {CredentialsError}
 */
async function issueStudentCredentials({ branchId, userId, email: requestedEmail }) {
  const ref = usersCol(branchId).doc(userId);
  const snap = await ref.get();
  if (!snap.exists) throw new CredentialsError(404, 'not-found', 'الطالب غير موجود في هذا الفرع.');
  const profile = snap.data() || {};
  const studentBranch = profile.branchId || profile.branch;
  if (studentBranch && studentBranch !== branchId) {
    throw new CredentialsError(403, 'permission-denied', 'Student does not belong to your branch.');
  }
  if (String(profile.role || 'student') !== 'student') {
    throw new CredentialsError(403, 'permission-denied', 'Only student accounts can be managed here.');
  }

  const name = profile.name || profile.fullName || '';
  let existing = null;
  try {
    existing = await auth.getUser(userId);
  } catch (err) {
    if (err?.code !== 'auth/user-not-found') throw err;
  }

  const now = admin.firestore.FieldValue.serverTimestamp();

  if (existing) {
    if (!(profile.createdByAdmin === true && profile.mustChangePassword === true)) {
      throw new CredentialsError(409, 'password-already-set',
        'قام الطالب بتعيين كلمة مروره الخاصة — يمكنه استعمال «نسيت كلمة المرور» في صفحة الدخول.');
    }
    const password = generateTemporaryPassword();
    await auth.updateUser(userId, { password });
    // Any session opened with the previous temporary password is closed.
    await auth.revokeRefreshTokens(userId).catch(() => {});
    await ref.update({
      authAccountStatus: AUTH_ACCOUNT.ACTIVE,
      authAccountError: null,
      mustChangePassword: true,
      temporaryPasswordIssuedAt: now,
      updatedAt: now,
    });
    return { action: 'reset', uid: userId, name, email: existing.email || profile.email || '', temporaryPassword: password };
  }

  // No login account yet → create one with the SAME uid.
  const email = String(requestedEmail || profile.email || '').trim().toLowerCase();
  if (!email) throw new CredentialsError(400, 'email-required', 'أدخل البريد الإلكتروني لإنشاء حساب الدخول.');
  if (!EMAIL_RE.test(email)) throw new CredentialsError(400, 'invalid-email', 'صيغة البريد الإلكتروني غير صحيحة.');

  // The email must not belong to another student of this branch.
  const sameEmail = await usersCol(branchId).where('email', '==', email).get();
  if (sameEmail.docs.some((d) => d.id !== userId)) {
    throw new CredentialsError(409, 'email-taken', 'هذا البريد مسجل لطالب آخر في الفرع.');
  }

  const password = generateTemporaryPassword();
  try {
    await createAuthUser({ uid: userId, email, password, displayName: name, emailVerified: true });
  } catch (err) {
    const code = safeAuthCode(err);
    await ref.update({ authAccountStatus: AUTH_ACCOUNT.FAILED, authAccountError: code, updatedAt: now }).catch(() => {});
    if (code === 'auth/email-already-exists') {
      throw new CredentialsError(409, 'email-taken', accountErrorMessage(code));
    }
    throw new CredentialsError(502, code, accountErrorMessage(code));
  }
  await ref.update({
    email,
    emailVerified: true,
    authAccountStatus: AUTH_ACCOUNT.ACTIVE,
    authAccountError: null,
    mustChangePassword: true,
    temporaryPasswordIssuedAt: now,
    updatedAt: now,
  });
  return { action: 'created', uid: userId, name, email, temporaryPassword: password };
}

